from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse
from fpdf import FPDF
import os
from database.connection import SessionLocal
from database.models import Alert

router = APIRouter()

# Ensure reports directory exists for saving the PDFs
reports_dir = os.path.join(os.path.dirname(__file__), "..", "..", "reports")
os.makedirs(reports_dir, exist_ok=True)

@router.get("/export-pdf/{alert_id}")
def export_pdf(alert_id: int):
    db = SessionLocal()
    try:
        alert = db.query(Alert).filter(Alert.id == alert_id).first()
        if not alert:
            raise HTTPException(status_code=404, detail="Alert not found")
            
        pdf = FPDF()
        pdf.add_page()
        
        # Header / Title
        pdf.set_font("Arial", 'B', 18)
        pdf.cell(200, 10, text="Automated Incident Response Report", ln=True, align='C')
        pdf.set_font("Arial", 'I', 10)
        pdf.cell(200, 10, text="Generated by Agentic Network Threat Platform", ln=True, align='C')
        pdf.ln(10)
        
        # Incident Details
        pdf.set_font("Arial", 'B', 14)
        pdf.cell(200, 10, text="Incident Details:", ln=True)
        
        pdf.set_font("Arial", '', 12)
        pdf.cell(200, 8, text=f"Incident ID: {alert.id}", ln=True)
        pdf.cell(200, 8, text=f"Timestamp: {alert.timestamp}", ln=True)
        pdf.cell(200, 8, text=f"Attack Type: {alert.alert_type}", ln=True)
        pdf.cell(200, 8, text=f"Attacker IP: {alert.source_ip}", ln=True)
        pdf.cell(200, 8, text=f"Risk Level: {alert.risk_level}", ln=True)
        pdf.cell(200, 8, text=f"Threat Score: {alert.threat_score}/100", ln=True)
        
        pdf.ln(10)
        
        # Explainable AI Reasons
        pdf.set_font("Arial", 'B', 14)
        pdf.cell(200, 10, text="Explainable AI (XAI) Reasons:", ln=True)
        
        pdf.set_font("Arial", '', 12)
        # Clean up the HTML tags (<br>, <b>) we used for the web dashboard so it prints nicely in PDF
        clean_desc = alert.description.replace('<br>', '\n').replace('<b>', '').replace('</b>', '')
        pdf.multi_cell(0, 8, text=clean_desc)
        
        pdf.ln(10)
        
        # Action Taken
        pdf.set_font("Arial", 'B', 14)
        pdf.cell(200, 10, text="Action Taken:", ln=True)
        pdf.set_font("Arial", '', 12)
        if alert.risk_level == "HIGH":
            pdf.cell(200, 8, text="Active Defense Triggered: Windows Firewall block rule created.", ln=True)
        else:
            pdf.cell(200, 8, text="System Monitored. No active defense triggered.", ln=True)
            
        # Save and return the PDF file
        pdf_path = os.path.join(reports_dir, f"Incident_{alert.id}.pdf")
        pdf.output(pdf_path)
        
        return FileResponse(pdf_path, filename=f"Incident_Report_{alert.id}.pdf")
        
    finally:
        db.close()
